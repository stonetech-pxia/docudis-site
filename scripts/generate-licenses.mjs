// Writes src/content/docs/docs/licenses.mdx: the licenses of the third-party
// code and fonts that the built site ships. Run after changing dependencies:
//   node scripts/generate-licenses.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const pkg = (name) => JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'));
const read = (path) => readFileSync(join(root, path), 'utf8').trim();

// What ends up in dist/: page scripts and styles, the search UI and index
// code, and the fonts. Build-only tools (Vite, Shiki, sharp) are not listed.
const components = [
	{ name: 'Astro', package: 'astro', file: 'node_modules/astro/LICENSE' },
	{ name: 'Starlight', package: '@astrojs/starlight', file: 'node_modules/@astrojs/starlight/LICENSE' },
	{ name: 'Expressive Code', package: '@expressive-code/core', file: 'node_modules/@expressive-code/core/LICENSE' },
	{ name: 'Pagefind and Pagefind UI', package: 'pagefind', file: 'scripts/licenses/pagefind.txt' },
	{ name: 'Svelte (inside Pagefind UI)', version: '4', license: 'MIT', file: 'scripts/licenses/svelte.txt' },
	{ name: 'mark.js (inside Pagefind)', version: '8', license: 'MIT', file: 'scripts/licenses/mark.js.txt' },
	{ name: 'Sora font', package: '@fontsource-variable/sora', file: 'node_modules/@fontsource-variable/sora/LICENSE' },
	{ name: 'Karla font', package: '@fontsource-variable/karla', file: 'node_modules/@fontsource-variable/karla/LICENSE' },
];

let out = `---
title: Open-source licenses
description: The licenses of this website and of the third-party code and fonts it uses.
---

{/* Generated by scripts/generate-licenses.mjs. Do not edit by hand. */}

The code and text of this website are licensed under the [Apache License 2.0](https://github.com/stonetech-pxia/docudis-site/blob/main/LICENSE), Copyright 2026 stonetech. The Docudis name and logo are not covered by that license, and neither are the app screenshots.

ChatGPT, Claude, Gemini, Perplexity, DeepSeek and the other AI apps shown in the screenshots are trademarks of their owners. Docudis is not affiliated with or endorsed by them.

The apps list their own open-source licenses under **Account** (Android) or **Settings** (desktop) > **Open-source licenses**.

The website includes the following third-party software and fonts.
`;

for (const c of components) {
	const info = c.package ? pkg(c.package) : {};
	const version = c.version ?? info.version;
	const license = c.license ?? info.license;
	out += `\n## ${c.name}\n\nVersion ${version}, ${license}.\n\n\`\`\`text\n${read(c.file)}\n\`\`\`\n`;
}

writeFileSync(join(root, 'src/content/docs/docs/licenses.mdx'), out);
console.log(`wrote ${components.length} components`);
